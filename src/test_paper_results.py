class TerminalColors:
    OKGREEN = '\033[92m'
    FAIL = '\033[91m'
    WARNING = '\033[93m'
    ENDC = '\033[0m'

def load_summary_csv(csv_path):
    """Parse the summarized CSV generated by summarize_label_efficiency.py"""
    metrics_data = {}
    with open(csv_path, newline='') as f:
        reader = csv.DictReader(f)
        for row in reader:
            metric = row['metric']
            metrics_data[metric] = {}
            for k, v in row.items():
                if k.endswith('_mean') and v.strip() and v.strip() != 'nan':
                    frac = k.replace('_mean', '')
                    metrics_data[metric][frac] = float(v)
    return metrics_data

def run_experiment(pipeline, is_fast):
    """Run the VAE training, label eff probing, and summarization using subprocess."""
    print(TerminalColors.WARNING + f"[*] Running full {pipeline} pipeline (fast={is_fast}). This may take a while..." + TerminalColors.ENDC)
    
    out_root = f"checkpoints/test_repro_{pipeline}"
    out_prefix = f"../experiments/label_eff_results_repro_{pipeline}"
    
    # 1. Train VAE
    train_cmd = [
        "./hetero_scripts/run_train_vae.sh",
        "--pipeline", "combined" if pipeline == "hetero" else "sean", # The provided scripts support 'combined' or 'sean'
        "--out-root", out_root
    ]
    if is_fast:
        train_cmd.extend(["--n-vaes", "1", "--epochs", "2"])
    
    print(" ->", " ".join(train_cmd))
    subprocess.run(train_cmd, check=True)
    
    # 2. Run Label Efficiency
    label_cmd = [
        "./hetero_scripts/run_label_eff.sh",
        "--pipeline", "combined" if pipeline == "hetero" else "sean",
        "--vae-root", out_root,
        "--out-prefix", out_prefix
    ]
    if is_fast:
        label_cmd.extend(["--n-vaes", "1", "--extra", "--epochs 5"])
    
    print(" ->", " ".join(label_cmd))
    subprocess.run(label_cmd, check=True)
    
    # 3. Summarize
    merged_csv = f"{out_prefix}.csv"
    summ_cmd = [
        "./hetero_scripts/run_summarize.sh",
        "--pipeline", "combined" if pipeline == "hetero" else "sean",
        "--in-prefix", out_prefix,
        "--merged", merged_csv
    ]
    if is_fast:
        summ_cmd.extend(["--n-vaes", "1"])
        
    print(" ->", " ".join(summ_cmd))
    subprocess.run(summ_cmd, check=True)
    
    # After summarization, the script generates `summary_sean.csv` and `summary_snsb.csv`
    # Let's return the paths
    return "../experiments/summary_sean.csv", "../experiments/summary_snsb.csv"

def compare_results(results, ground_truth, stds, flat_tolerance=None):
    """Compare generated results against the paper's ground truth."""
    all_passed = True
    tol_desc = f"flat tolerance of {flat_tolerance}" if flat_tolerance is not None else "paper standard deviations"
    print(f"\n{'-'*60}\nComparison Results (Allowed diff based on {tol_desc})\n{'-'*60}")
    
    for task, task_metrics in ground_truth.items():
        if task not in results:
            continue
        
        for metric, frac_dict in task_metrics.items():
            if metric not in results[task]:
                print(TerminalColors.FAIL + f"[FAIL] Metric '{metric}' not found in generated results for task '{task}'" + TerminalColors.ENDC)
                all_passed = False
                continue
                
            for frac, paper_val in frac_dict.items():
                if frac not in results[task][metric]:
                    print(TerminalColors.FAIL + f"[FAIL] Fraction '{frac}' not found for metric '{metric}'" + TerminalColors.ENDC)
                    all_passed = False
                    continue
                
                gen_val = results[task][metric][frac]
                diff = abs(gen_val - paper_val)
                
                if flat_tolerance is not None:
                    tolerance = flat_tolerance
                else:
                    tolerance = stds[task][metric][frac]
                
                if diff <= tolerance:
                    status = TerminalColors.OKGREEN + "[PASS]" + TerminalColors.ENDC
                else:
                    status = TerminalColors.FAIL + "[FAIL]" + TerminalColors.ENDC
                    all_passed = False
                    
                print(f"{status} {task.upper()} - {metric} @ {frac}: Paper={paper_val:.3f}, Generated={gen_val:.3f} (Diff={diff:.3f}, Allowed={tolerance:.3f})")
                
    return all_passed

def main():
    parser = argparse.ArgumentParser(description="Test Harness for SWM CORL Paper Results")
    parser.add_argument("--run-all", action="store_true", help="Run all experiments (both heterogeneous and homogeneous pipelines)")
    parser.add_argument("--run-hetero", action="store_true", help="Run the heterogeneous pipeline from scratch")
    parser.add_argument("--run-homo", action="store_true", help="Run the homogeneous pipeline from scratch")
    parser.add_argument("--fast", action="store_true", help="Run a fast, smaller sweep for debugging")
    parser.add_argument("--csv-sean", type=str, help="Path to precomputed SEAN summary CSV")
    parser.add_argument("--csv-sns", type=str, help="Path to precomputed SNS summary CSV")
    parser.add_argument("--tolerance", type=float, default=None, help="Custom flat absolute tolerance for F1-score comparison (overrides paper standard deviations if set)")
    args = parser.parse_args()

    results_hetero = {}
    results_homo = {}
    os.makedirs("../experiments", exist_ok=True)
    
    run_hetero_flag = args.run_hetero or args.run_all
    run_homo_flag = args.run_homo or args.run_all

    # Default to run-all if no flags at all are provided
    if not (args.run_hetero or args.run_homo or args.run_all or args.csv_sean or args.csv_sns):
        run_hetero_flag = True
        run_homo_flag = True

    # If user provided manual CSVs
    if args.csv_sean or args.csv_sns:
        results = {}
        if args.csv_sean:
            results["sean"] = load_summary_csv(args.csv_sean)
        if args.csv_sns:
            results["snsb"] = load_summary_csv(args.csv_sns)
        # Default to comparing against hetero if manual csv
        gt = PAPER_RESULTS["hetero"]
        passed = compare_results(results, gt, PAPER_STDS["hetero"], args.tolerance)
        if passed:
            print(TerminalColors.OKGREEN + "\n[SUCCESS] All checked metrics matched within the allowed tolerance." + TerminalColors.ENDC)
        else:
            print(TerminalColors.FAIL + "\n[WARNING] Some metrics exceeded the allowed tolerance." + TerminalColors.ENDC)
        return

    all_passed = True

    if run_hetero_flag:
        print("\n" + "="*60 + "\nRUNNING HETEROGENEOUS EXPERIMENTS\n" + "="*60)
        sean_csv, sns_csv = run_experiment("hetero", args.fast)
        results_hetero["sean"] = load_summary_csv(sean_csv)
        results_hetero["snsb"] = load_summary_csv(sns_csv)
        
        gt = PAPER_RESULTS["hetero"]
        passed = compare_results(results_hetero, gt, PAPER_STDS["hetero"], args.tolerance)
        all_passed = all_passed and passed

    if run_homo_flag:
        print("\n" + "="*60 + "\nRUNNING HOMOGENEOUS EXPERIMENTS\n" + "="*60)
        sean_csv, sns_csv = run_experiment("homo", args.fast)
        results_homo["sean"] = load_summary_csv(sean_csv)
        if os.path.exists(sns_csv):
            results_homo["snsb"] = load_summary_csv(sns_csv)
        
        gt = PAPER_RESULTS["homo"]
        passed = compare_results(results_homo, gt, PAPER_STDS["homo"], args.tolerance)
        all_passed = all_passed and passed

    if all_passed:
        print(TerminalColors.OKGREEN + "\n[SUCCESS] All checked metrics matched within the allowed tolerance." + TerminalColors.ENDC)
    else:
        print(TerminalColors.FAIL + "\n[WARNING] Some metrics exceeded the allowed tolerance." + TerminalColors.ENDC)

if __name__ == "__main__":
    main()
